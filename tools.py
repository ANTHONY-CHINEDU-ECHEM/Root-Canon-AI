"""Deterministic clinical tools.

Numbers that could harm a patient if wrong (doses, maximum local anaesthetic
volumes, interactions) are never generated by the language model. They come
from this module, which reads a version controlled formulary file, performs
exact arithmetic and always returns the source link alongside the result.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import yaml

FORMULARY_PATH = Path(__file__).with_name("uk_dental_formulary.yaml")


@lru_cache(maxsize=1)
def formulary() -> dict:
    return yaml.safe_load(FORMULARY_PATH.read_text(encoding="utf-8"))


def _source(key: str) -> str:
    return formulary()["sources"].get(key, "")


@dataclass
class RegimenResult:
    drug: str
    population: str
    dose: str
    frequency: str
    duration: str | None
    indication: str
    note: str
    source_url: str
    reviewed: str
    verify_message: str = (
        "Reference only. Confirm against the current BNF or BNFC and the patient's history before prescribing."
    )


def lookup_regimen(drug: str, age_years: float | None = None) -> RegimenResult:
    key = drug.strip().lower().replace(" ", "")
    regimens = formulary()["regimens"]
    if key not in regimens:
        raise KeyError(f"No UK dental regimen on file for '{drug}'. Available: {', '.join(sorted(regimens))}")
    entry = regimens[key]
    reviewed = formulary()["reviewed"]
    if age_years is not None and age_years < 18:
        for band in entry.get("child_bands", []):
            if band["min_age_years"] <= age_years < band["max_age_years"]:
                return RegimenResult(key, f"child aged {age_years:g} years", band["dose"], band["frequency"],
                                     entry["adult"].get("duration"), entry["indication"], entry["note"],
                                     _source(entry["source"]), reviewed)
        raise ValueError(f"No paediatric band on file for {key} at age {age_years:g}; consult the BNFC.")
    adult = entry["adult"]
    return RegimenResult(key, "adult", adult["dose"], adult["frequency"], adult.get("duration"),
                         entry["indication"], entry["note"], _source(entry["source"]), reviewed)


def adrenaline_dose(age_years: float) -> dict:
    entry = formulary()["emergency"]["adrenaline_anaphylaxis"]
    for band in entry["age_bands"]:
        if band["min_age_years"] <= age_years < band["max_age_years"]:
            return {"title": entry["title"], "dose": band["dose"], "repeat": entry["repeat"],
                    "source_url": _source(entry["source"])}
    raise ValueError("Age out of range")


@dataclass
class LocalAnaestheticLimit:
    product: str
    weight_kg: float
    max_mg: float
    max_ml: float
    max_cartridges: float
    basis: str


def local_anaesthetic_max(product_name: str, weight_kg: float) -> LocalAnaestheticLimit:
    if not 3 <= weight_kg <= 250:
        raise ValueError("Weight must be between 3 and 250 kg")
    products = {p["name"].lower(): p for p in formulary()["local_anaesthetics"]}
    match = next((p for name, p in products.items() if product_name.lower() in name), None)
    if match is None:
        raise KeyError(f"Unknown local anaesthetic '{product_name}'")
    max_mg = min(match["max_mg_per_kg"] * weight_kg, match["absolute_max_mg"])
    max_ml = max_mg / match["mg_per_ml"]
    return LocalAnaestheticLimit(
        product=match["name"], weight_kg=weight_kg, max_mg=round(max_mg, 1), max_ml=round(max_ml, 2),
        max_cartridges=round(max_ml / match["cartridge_ml"], 1),
        basis=f"{match['max_mg_per_kg']} mg/kg, ceiling {match['absolute_max_mg']} mg, "
              f"{match['mg_per_ml']} mg/mL, {match['cartridge_ml']} mL cartridge. Confirm against the SmPC.",
    )


def check_interactions(drugs: list[str]) -> list[dict]:
    names = {d.strip().lower() for d in drugs if d.strip()}
    hits = []
    for rule in formulary()["interactions"]:
        if rule["a"] in names and rule["b"] in names:
            hits.append(rule)
    severity_order = {"major": 0, "moderate": 1, "minor": 2}
    return sorted(hits, key=lambda r: severity_order.get(r["severity"], 3))
